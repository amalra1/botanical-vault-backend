CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE origins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    position INTEGER NOT NULL
);

CREATE TABLE plant_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    position INTEGER NOT NULL
);

CREATE TABLE sizes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    description VARCHAR(80),
    position INTEGER NOT NULL
);

CREATE TABLE image_views (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    position INTEGER NOT NULL
);

CREATE TABLE plants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    common_name VARCHAR(160) NOT NULL,
    scientific_name VARCHAR(160),
    type_id BIGINT NOT NULL REFERENCES plant_types (id),
    size_id BIGINT NOT NULL REFERENCES sizes (id),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX plants_type_id_idx ON plants (type_id);
CREATE INDEX plants_size_id_idx ON plants (size_id);

CREATE TABLE plant_origins (
    plant_id BIGINT NOT NULL REFERENCES plants (id) ON DELETE CASCADE,
    origin_id BIGINT NOT NULL REFERENCES origins (id) ON DELETE CASCADE,
    PRIMARY KEY (plant_id, origin_id)
);

CREATE INDEX plant_origins_origin_id_idx ON plant_origins (origin_id);

CREATE TABLE plant_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id BIGINT NOT NULL REFERENCES plants (id) ON DELETE CASCADE,
    view_id BIGINT NOT NULL REFERENCES image_views (id),
    storage_key VARCHAR(255) NOT NULL UNIQUE,
    original_filename VARCHAR(255) NOT NULL,
    position INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX plant_images_plant_id_position_idx ON plant_images (plant_id, position);
CREATE INDEX plant_images_view_id_idx ON plant_images (view_id);

CREATE TABLE collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    is_favorites BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX collections_single_favorites_idx ON collections (is_favorites) WHERE is_favorites;

CREATE TABLE collection_plants (
    collection_id BIGINT NOT NULL REFERENCES collections (id) ON DELETE CASCADE,
    plant_id BIGINT NOT NULL REFERENCES plants (id) ON DELETE CASCADE,
    added_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (collection_id, plant_id)
);

CREATE INDEX collection_plants_plant_id_idx ON collection_plants (plant_id);
